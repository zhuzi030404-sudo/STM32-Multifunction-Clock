/* OLED（有机发光显示屏）驱动：128列×64行像素，PB8=SCL时钟、PB9=SDA数据，软件I2C通信。
 * 屏幕按8个page存储，每个page是一条高8像素的横带，不是主菜单的“页面”。
 * 一个字节控制同一列的8个像素；page范围0到7，x范围0到127，像素y范围0到63。
 * FrameBuffer 是绘图草稿；Desired 是最终期望画面；DisplayValid 表示对应横带已成功同步。
 * 文字直接更新期望画面，绘图先改草稿、再调用UpdateFrame/Area传送指定区域。
 * 通信中ACK（应答）表示对方已接收；数据线开漏输出1是释放线路，需要上拉才能变高。 */
#include "main.h"
#include "oled.h"
#include <string.h>

/* 绘图草稿：8×128=1024字节，每字节代表竖向8个像素。 */
static uint8_t OLED_FrameBuffer[8][128];
/* 最终期望画面；即使本次发送失败也保留内容，以便恢复时补发。 */
static uint8_t OLED_Desired[8][128];
/* 每条横带是否已成功同步；断线后清零，不能再假定屏幕内容与缓存一致。 */
static uint8_t OLED_DisplayValid[8];
/* 通信状态，0待重连，1表示最近连接成功，不等于持续监测每个电气故障。 */
static uint8_t OLED_Connected = 0;
/* 记住用户希望亮屏还是息屏，恢复连接时沿用。 */
static uint8_t OLED_WantedOn = 1;
/* 当前目标对比度参数，亮度调节最终修改这里。 */
static uint8_t OLED_Contrast = 0xCF;
/* 上次失败或尝试重连的毫秒时刻，限制重试频率。 */
static uint32_t OLED_RetryAt = 0;

/* 记录通信失败，作废已同步标记，交给Service稍后重新连接；期望画面不清除。 */
static void OLED_Disconnect(void)
{
    OLED_Connected = 0;
    OLED_RetryAt = HAL_GetTick();
    memset(OLED_DisplayValid, 0, sizeof(OLED_DisplayValid));
}

/* 用DWT处理器周期计数器等待约5微秒，保持软件总线的基本时序。 */
static void OLED_Delay(void)
{
    uint32_t start = DWT->CYCCNT;
    uint32_t ticks = (SystemCoreClock / 1000000U) * 5U;

    while ((uint32_t)(DWT->CYCCNT - start) < ticks)
    {
    }
}

/* 设置PB8时钟线并等待电平稳定。 */
static void OLED_WriteSCL(uint8_t level)
{
    if (level == 0)
    {
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_8, GPIO_PIN_RESET);
    }
    else
    {
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_8, GPIO_PIN_SET);
    }
    OLED_Delay();
}

/* 设置PB9数据线并等待；1释放线路，0主动拉低。 */
static void OLED_WriteSDA(uint8_t level)
{
    if (level == 0)
    {
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_9, GPIO_PIN_RESET);
    }
    else
    {
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_9, GPIO_PIN_SET);
    }
    OLED_Delay();
}

/* SCL高电平期间，SDA从高变低表示开始一笔通信。 */
static void OLED_Start(void)
{
    OLED_WriteSDA(1);
    OLED_WriteSCL(1);
    OLED_WriteSDA(0);
    OLED_WriteSCL(0);
}

/* SCL高电平期间，SDA从低变高表示结束通信。 */
static void OLED_Stop(void)
{
    OLED_WriteSDA(0);
    OLED_WriteSCL(1);
    OLED_WriteSDA(1);
}

/* 先发最高位，共8位；第9个时钟确认时钟线为高且数据线被屏幕拉低，即收到ACK。 */
static uint8_t OLED_SendByte(uint8_t data)
{
    for (uint8_t i = 0; i < 8; i++)
    {
        if ((data & 0x80) != 0)
        {
            OLED_WriteSDA(1);
        }
        else
        {
            OLED_WriteSDA(0);
        }

        OLED_WriteSCL(1);
        OLED_WriteSCL(0);

        data <<= 1;
    }

    OLED_WriteSDA(1);
    OLED_WriteSCL(1);
    uint8_t acknowledged =
        HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_8) == GPIO_PIN_SET &&
        HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_9) == GPIO_PIN_RESET;
    OLED_WriteSCL(0);
    return acknowledged;
}

/* 0x78是包含写方向位的设备地址（7位地址0x3C）；0x00表示后面发送控制命令。 */
static uint8_t OLED_WriteCommand(uint8_t command)
{
    OLED_Start();
    uint8_t ok = OLED_SendByte(0x78) &&
                 OLED_SendByte(0x00) && OLED_SendByte(command);
    OLED_Stop();
    return ok;
}

/* 记录希望亮屏并发送0xAF；若断线，恢复连接后仍按这个状态处理。 */
void OLED_DisplayOn(void)
{
    OLED_WantedOn = 1;
    if (OLED_Connected && !OLED_WriteCommand(0xAF))
        OLED_Disconnect();
}

/* 记录希望息屏并发送0xAE；这里只关显示输出，主控程序继续运行。 */
void OLED_DisplayOff(void)
{
    OLED_WantedOn = 0;
    if (OLED_Connected && !OLED_WriteCommand(0xAE))
        OLED_Disconnect();
}

/* 0x81命令调整对比度以改变亮度；相同数值不重复发送，断线时仍保存目标值。 */
void OLED_SetContrast(uint8_t contrast)
{
    if (contrast == OLED_Contrast)
        return;
    OLED_Contrast = contrast;
    if (OLED_Connected &&
        (!OLED_WriteCommand(0x81) || !OLED_WriteCommand(contrast)))
        OLED_Disconnect();
}

/* 设置写入起点：page是8像素横带，x是列；加2列偏移沿用当前屏幕适配。 */
static uint8_t OLED_SetCursor(uint8_t page, uint8_t x)
{
    x += 2;
    return OLED_WriteCommand(0xB0 | page) &&
           OLED_WriteCommand(0x10 | (x >> 4)) &&
           OLED_WriteCommand(x & 0x0F);
}

/* 连续发送count列像素，0x40表示像素数据；任何传输失败都标记断线。 */
static uint8_t OLED_SendSpan(uint8_t page, uint8_t x,
                            const uint8_t *data, uint8_t count)
{
    if (!OLED_SetCursor(page, x))
    {
        OLED_Disconnect();
        return 0;
    }
    OLED_Start();
    uint8_t ok = OLED_SendByte(0x78) && OLED_SendByte(0x40);
    for (uint16_t i = 0; ok && i < count; i++)
        ok = OLED_SendByte(data[i]);
    OLED_Stop();
    if (!ok)
        OLED_Disconnect();
    return ok;
}

/* 先找出变化范围，再保存期望画面并发送；只在发送成功后承认画面已同步。 */
static void OLED_WriteSpan(uint8_t page, uint8_t x,
                            const uint8_t *data, uint8_t count)
{
    if (page >= 8U || x >= 128U || count == 0U || count > 128U - x)
        return;
    /* 用[first,end)半开区间表示待发送数据：包含first，不包含end。 */
    uint16_t first = 0;
    uint16_t end = count;
    if (OLED_DisplayValid[page])
    {
        while (first < end && OLED_Desired[page][x + first] == data[first])
            first++;
        while (end > first && OLED_Desired[page][x + end - 1U] == data[end - 1U])
            end--;
    }
    /* Keep the requested pixels even when a one-time title cannot be sent. */
    /* memcpy按字节复制：目标地址、源地址、字节数；这里保存最新期望内容。 */
    memcpy(&OLED_Desired[page][x], data, count);
    if (!OLED_Connected)
        return;
    if (!OLED_DisplayValid[page])
    {
        x = 0;
        first = 0;
        end = 128;
    }
    if (first < end && OLED_SendSpan(page, x + first,
                                    &OLED_Desired[page][x + first], end - first))
        OLED_DisplayValid[page] = 1;
}

/* 用一个字节图案填满屏幕：0x00全灭、0xFF全亮，其他值可形成条纹。 */
void OLED_Fill(uint8_t pattern)
{
    uint8_t data[128];
    memset(data, pattern, sizeof(data));
    for (uint8_t page = 0; page < 8; page++)
        OLED_WriteSpan(page, 0, data, sizeof(data));
}

/* 尝试释放卡住的数据线，再重新下发控制器配置，恢复目标亮度与亮屏状态。 */
static uint8_t OLED_Reconnect(void)
{
    OLED_WriteSDA(1);
    OLED_WriteSCL(1);
    if (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_8) == GPIO_PIN_RESET)
        return 0;
    if (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_9) == GPIO_PIN_RESET)
    {
        for (uint8_t i = 0; i < 9; i++)
        {
            OLED_WriteSCL(0);
            OLED_WriteSCL(1);
        }
    }
    OLED_Stop();
    if (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_9) == GPIO_PIN_RESET)
        return 0;
    /* 控制器命令表：关闭显示后配置扫描时序、64行复用、方向、预充电和电荷泵，再恢复亮度。
     * 这些数值对应当前屏幕控制器，换屏应查对应手册，不要把它们当作图案数据。 */
    const uint8_t commands[] =
    {
        0xAE,
        0xD5, 0x80,
        0xA8, 0x3F,
        0xD3, 0x00,
        0x40,
        0xA1,
        0xC8,
        0xDA, 0x12,
        0xD9, 0xF1,
        0xDB, 0x30,
        0xA4,
        0xA6,
        0x8D, 0x14
    };

    for (uint32_t i = 0; i < sizeof(commands); i++)
        if (!OLED_WriteCommand(commands[i]))
            return 0;
    if (!OLED_WriteCommand(0x81) || !OLED_WriteCommand(OLED_Contrast))
        return 0;
    return OLED_WriteCommand(OLED_WantedOn ? 0xAF : 0xAE);
}

/* 主循环维护函数：断线每100毫秒重试，连接后每次最多恢复一条8像素横带。 */
void OLED_Service(void)
{
    if (!OLED_Connected)
    {
        uint32_t now = HAL_GetTick();
        if ((uint32_t)(now - OLED_RetryAt) < 100U)
            return;
        OLED_RetryAt = now;
        if (!OLED_Reconnect())
            return;
        OLED_Connected = 1;
        memset(OLED_DisplayValid, 0, sizeof(OLED_DisplayValid));
    }
    /* Restore at most one 8-pixel strip before returning to key polling. */
    for (uint8_t page = 0; page < 8; page++)
    {
        if (!OLED_DisplayValid[page])
        {
            if (OLED_SendSpan(page, 0, OLED_Desired[page], 128))
                OLED_DisplayValid[page] = 1;
            return;
        }
    }
}

/* 初始化缓存和微秒延时，等待屏幕上电，再尝试连接并清屏。 */
void OLED_Init(void)
{
    memset(OLED_Desired, 0, sizeof(OLED_Desired));
    memset(OLED_DisplayValid, 0, sizeof(OLED_DisplayValid));
    OLED_Connected = 0;
    OLED_WantedOn = 1;
    OLED_Contrast = 0xCF;
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CYCCNT = 0;
    DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
    HAL_Delay(100);
    OLED_RetryAt = HAL_GetTick() - 100U;
    OLED_Service();
    OLED_Fill(0x00);
}


/* 早期连屏检查用的固定Hello显示函数。 */
void OLED_ShowHello(uint8_t page, uint8_t x)
{
    const uint8_t font[6][5] =
    {
        {0x7F, 0x08, 0x08, 0x08, 0x7F},  /* H */
        {0x38, 0x54, 0x54, 0x54, 0x18},  /* e */
        {0x00, 0x41, 0x7F, 0x40, 0x00},  /* l */
        {0x00, 0x41, 0x7F, 0x40, 0x00},  /* l */
        {0x38, 0x44, 0x44, 0x44, 0x38},  /* o */
        {0x00, 0x00, 0x5F, 0x00, 0x00}   /* ! */
    };

    uint8_t data[36];
    for (uint8_t character = 0; character < 6; character++)
    {
        memcpy(&data[character * 6U], font[character], 5);
        data[character * 6U + 5U] = 0;
    }
    OLED_WriteSpan(page, x, data, sizeof(data));
}

/* 把一个数字对应的点阵字节复制到输出数组；图案表本身不需要逐个背诵。 */
static void OLED_WriteDigit(uint8_t digit, uint8_t *data)
{
    const uint8_t font[10][5] =
    {
        {0x3E, 0x51, 0x49, 0x45, 0x3E},  /* 0 */
        {0x00, 0x42, 0x7F, 0x40, 0x00},  /* 1 */
        {0x42, 0x61, 0x51, 0x49, 0x46},  /* 2 */
        {0x21, 0x41, 0x45, 0x4B, 0x31},  /* 3 */
        {0x18, 0x14, 0x12, 0x7F, 0x10},  /* 4 */
        {0x27, 0x45, 0x45, 0x45, 0x39},  /* 5 */
        {0x3C, 0x4A, 0x49, 0x49, 0x30},  /* 6 */
        {0x01, 0x71, 0x09, 0x05, 0x03},  /* 7 */
        {0x36, 0x49, 0x49, 0x49, 0x36},  /* 8 */
        {0x06, 0x49, 0x49, 0x29, 0x1E}   /* 9 */
    };

    memcpy(data, font[digit], 5);
    data[5] = 0;
}

/* 在指定page和x显示定长十进制数；长度决定显示位数，前导空位用0补足。 */
void OLED_ShowNum(uint8_t page, uint8_t x,
                  uint32_t number, uint8_t length)
{
    if (length == 0U || length > 10U || page > 7U || x + length * 6U > 128U)
        return;
    uint8_t data[60];
    uint32_t divisor = 1;
    for (uint8_t i = 1; i < length; i++)
        divisor *= 10;
    for (uint8_t i = 0; i < length; i++)
    {
        OLED_WriteDigit((number / divisor) % 10U, &data[i * 6U]);
        divisor /= 10;
    }
    OLED_WriteSpan(page, x, data, length * 6U);
}

/* 把支持的ASCII字符（字母、数字等单字节字符）转换为点阵，未知字符画空白。 */
static void OLED_WriteChar(char ch, uint8_t *data)
{
    static const uint8_t letters[26][5] =
    {
        {0x7E,0x11,0x11,0x11,0x7E}, /* A */
        {0x7F,0x49,0x49,0x49,0x36}, /* B */
        {0x3E,0x41,0x41,0x41,0x22}, /* C */
        {0x7F,0x41,0x41,0x22,0x1C}, /* D */
        {0x7F,0x49,0x49,0x49,0x41}, /* E */
        {0x7F,0x09,0x09,0x09,0x01}, /* F */
        {0x3E,0x41,0x49,0x49,0x7A}, /* G */
        {0x7F,0x08,0x08,0x08,0x7F}, /* H */
        {0x00,0x41,0x7F,0x41,0x00}, /* I */
        {0x20,0x40,0x41,0x3F,0x01}, /* J */
        {0x7F,0x08,0x14,0x22,0x41}, /* K */
        {0x7F,0x40,0x40,0x40,0x40}, /* L */
        {0x7F,0x02,0x0C,0x02,0x7F}, /* M */
        {0x7F,0x04,0x08,0x10,0x7F}, /* N */
        {0x3E,0x41,0x41,0x41,0x3E}, /* O */
        {0x7F,0x09,0x09,0x09,0x06}, /* P */
        {0x3E,0x41,0x51,0x21,0x5E}, /* Q */
        {0x7F,0x09,0x19,0x29,0x46}, /* R */
        {0x46,0x49,0x49,0x49,0x31}, /* S */
        {0x01,0x01,0x7F,0x01,0x01}, /* T */
        {0x3F,0x40,0x40,0x40,0x3F}, /* U */
        {0x1F,0x20,0x40,0x20,0x1F}, /* V */
        {0x3F,0x40,0x38,0x40,0x3F}, /* W */
        {0x63,0x14,0x08,0x14,0x63}, /* X */
        {0x07,0x08,0x70,0x08,0x07}, /* Y */
        {0x61,0x51,0x49,0x45,0x43}  /* Z */
    };

    static const uint8_t blank[5] = {0,0,0,0,0};
    static const uint8_t colon[5] = {0,0x36,0x36,0,0};
    static const uint8_t dash[5] = {0x08,0x08,0x08,0x08,0x08};
    static const uint8_t arrow[5] = {0,0x41,0x22,0x14,0x08};
    static const uint8_t plus[5] = {0x08,0x08,0x3E,0x08,0x08};
    static const uint8_t percent[5] = {0x62,0x64,0x08,0x13,0x23};

    if (ch >= 'a' && ch <= 'z')
    {
        ch = ch - 'a' + 'A';
    }

    if (ch >= '0' && ch <= '9')
    {
        OLED_WriteDigit(ch - '0', data);
        return;
    }

    const uint8_t *glyph = blank;

    if (ch >= 'A' && ch <= 'Z')
    {
        glyph = letters[ch - 'A'];
    }
    else if (ch == ':')
    {
        glyph = colon;
    }
    else if (ch == '-')
    {
        glyph = dash;
    }
    else if (ch == '>')
    {
        glyph = arrow;
    }
    else if (ch == '%')
    {
        glyph = percent;
    }
    else if (ch == '+')
    {
        glyph = plus;
    }

    memcpy(data, glyph, 5);
    data[5] = 0;
}

/* 按字符依次输出字符串；page是8像素横带编号，x是像素列。 */
void OLED_ShowString(uint8_t page, uint8_t x, const char *text)
{
    if (page > 7U || x > 122U)
        return;
    uint8_t data[126];
    uint8_t count = 0;
    while (*text != '\0' && x + count + 6U <= 128U)
    {
        OLED_WriteChar(*text++, &data[count]);
        count += 6U;
    }
    OLED_WriteSpan(page, x, data, count);
}

