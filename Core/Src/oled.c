/* 从本工程已有中文字库查找16×16点阵；每个常用汉字按UTF-8的3字节匹配，未收录则留空。 */
void OLED_ShowChinese(uint8_t page, uint8_t x, const char *text)
{
    if (page > 6U || x > 112U)
        return;
    while (text[0] != '\0' && text[1] != '\0' && text[2] != '\0' && x <= 112U)
    {
        const uint8_t *glyph = NULL;
        for (uint32_t i = 0; i < sizeof(OLED_ChineseFont) / sizeof(OLED_ChineseFont[0]); i++)
        {
            if (strncmp(text, OLED_ChineseFont[i].text, 3) == 0)
            {
                glyph = OLED_ChineseFont[i].pixels;
                break;
            }
        }
        static const uint8_t blank[32] = {0};
        if (glyph == NULL)
            glyph = blank;
        for (uint8_t row = 0; row < 2; row++)
            OLED_WriteSpan(page + row, x, &glyph[row * 16U], 16);
        text += 3;
        x += 16U;
    }
}

/* 只清空绘图草稿，不会直接清除屏幕，也不会清除已经显示的文字。 */
void OLED_FrameClear(void)
{
    memset(OLED_FrameBuffer, 0, sizeof(OLED_FrameBuffer));
}

/* 在草稿点亮一个像素：y/8选横带，y%8选字节中的位；越界像素忽略。 */
void OLED_DrawPoint(int16_t x, int16_t y)
{
    if (x >= 0 && x < 128 && y >= 0 && y < 64)
    {
        /* 例如像素(10,9)：第1横带的第10列，字节中第1位；|=只点亮该位，不擦其他像素。 */
        OLED_FrameBuffer[y / 8][x] |= (uint8_t)(1U << (y % 8));
    }
}

/* 用Bresenham整数步进画直线，通过误差累计选择下一个像素，减少浮点计算。 */
void OLED_DrawLine(int16_t x0, int16_t y0, int16_t x1, int16_t y1)
{
    int32_t dx = (x1 >= x0) ? (int32_t)x1 - x0 : (int32_t)x0 - x1;
    int32_t dy = (y1 >= y0) ? (int32_t)y0 - y1 : (int32_t)y1 - y0;
    int16_t sx = (x0 < x1) ? 1 : -1;
    int16_t sy = (y0 < y1) ? 1 : -1;
    int32_t error = dx + dy;

    for (;;)
    {
        OLED_DrawPoint(x0, y0);
        if (x0 == x1 && y0 == y1)
            break;
        int32_t twiceError = 2 * error;
        if (twiceError >= dy)
        {
            error += dy;
            x0 += sx;
        }
        if (twiceError <= dx)
        {
            error += dx;
            y0 += sy;
        }
    }
}

/* 按像素到圆心的距离画圆；filled=1为实心，0为圆环，并裁剪到屏幕范围。 */
void OLED_DrawCircle(int16_t centerX, int16_t centerY,
                     uint8_t radius, uint8_t filled)
{
    int32_t left = (int32_t)centerX - radius;
    int32_t right = (int32_t)centerX + radius;
    int32_t top = (int32_t)centerY - radius;
    int32_t bottom = (int32_t)centerY + radius;

    if (left < 0) left = 0;
    if (right > 127) right = 127;
    if (top < 0) top = 0;
    if (bottom > 63) bottom = 63;

    uint32_t radiusSquared = (uint32_t)radius * radius;

    for (int32_t y = top; y <= bottom; y++)
    {
        for (int32_t x = left; x <= right; x++)
        {
            int32_t dx = x - centerX;
            int32_t dy = y - centerY;
            uint32_t distance = (uint32_t)(dx * dx) + (uint32_t)(dy * dy);

            if ((filled && distance <= radiusSquared) ||
                (!filled &&
                 distance >= radiusSquared - radius &&
                 distance <= radiusSquared + radius))
            {
                OLED_DrawPoint((int16_t)x, (int16_t)y);
            }
        }
    }
}

/* 把草稿指定矩形同步到期望画面和屏幕；横向用像素，纵向用8像素横带计数。 */
void OLED_UpdateFrameArea(uint8_t firstPage, uint8_t pageCount,
                           uint8_t x, uint8_t width)
{
    if (firstPage >= 8U || pageCount == 0U || pageCount > 8U - firstPage ||
        x >= 128U || width == 0U || width > 128U - x)
        return;
    for (uint8_t page = firstPage; page < firstPage + pageCount; page++)
        OLED_WriteSpan(page, x, &OLED_FrameBuffer[page][x], width);
}

/* 同步从firstPage开始的pageCount条横带，每条宽128像素。 */
void OLED_UpdateFrame(uint8_t firstPage, uint8_t pageCount)
{
    OLED_UpdateFrameArea(firstPage, pageCount, 0, 128);
}
